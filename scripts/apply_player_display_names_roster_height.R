# Let player_display_names_v fall back to basket.co.il's team-page roster
# (basket_player_roster, 2026-11-12) for height_m and position_en where the
# season-stat table has none. Same columns; only NULL heights/positions fill.
#
# Built from the LIVE view definition (as apply_player_display_names_size.R):
# a roster_size CTE (verified rows, joined on identity AND team through
# schedule_team_dict, as the basket CTE is), a LEFT JOIN to it, and
# COALESCE(season, roster) in the two columns.
#
# Dry run by default: one transaction, every gate, then ROLLBACK.
# CONFIRM_DISPLAY_NAMES_ROSTER=1 commits. The DDL that ran is written to
# sql/migrations/2026-11-12_player_display_names_roster_height.sql.

confirm_apply <- identical(Sys.getenv("CONFIRM_DISPLAY_NAMES_ROSTER", "0"), "1")
readRenviron("etl/.Renviron")
suppressPackageStartupMessages({ library(DBI); library(RPostgres) })
con <- dbConnect(Postgres(), host = Sys.getenv("PG_HOST"), port = 5432L,
  dbname = Sys.getenv("PG_DB"), user = Sys.getenv("PG_USER"),
  password = Sys.getenv("PG_PASS"), sslmode = "require", bigint = "numeric")
on.exit(dbDisconnect(con))
q <- function(sql) dbGetQuery(con, sql)
x <- function(sql) invisible(dbExecute(con, sql))
view <- "basketball_test.player_display_names_v"
cols <- function() q(sprintf(
  "SELECT attname FROM pg_attribute WHERE attrelid = '%s'::regclass AND attnum > 0 AND NOT attisdropped ORDER BY attnum", view))$attname
snapshot <- function() q(sprintf(
  "SELECT game_year, team_id, player_id, md5(row(game_year, team_id, player_id, identity_id, display_name, display_name_he, name_source)::text) AS names, height_m, position_en FROM %s", view))

cat("mode:", if (confirm_apply) "APPLY (commits)" else "DRY RUN (rolls back)", "\n")
x("BEGIN")
ok <- FALSE
tryCatch({
  x("SET LOCAL lock_timeout = '5s'")
  x("SET LOCAL statement_timeout = '120s'")
  before_cols <- cols()
  if (!all(c("height_m", "position_en") %in% before_cols)) stop("apply apply_player_display_names_size.R first")
  before <- snapshot()
  def <- q(sprintf("SELECT pg_get_viewdef('%s'::regclass, true) AS d", view))$d
  if (grepl("roster_size", def, fixed = TRUE)) stop("view already falls back to the roster")
  edit <- function(text, pattern, replacement, what) {
    hits <- gregexpr(pattern, text, perl = TRUE)[[1]]
    if (length(hits) != 1 || hits[1] < 0) stop("expected exactly one match for ", what)
    sub(pattern, replacement, text, perl = TRUE)
  }
  def <- edit(def, "(GROUP BY b\\.game_year, d\\.team_id_rosters, b\\.identity_id\\s*\\))(\\s*SELECT)",
    paste0("\\1, roster_size AS (\n         SELECT r.game_year,\n            d.team_id_rosters AS team_id,\n",
           "            r.identity_id,\n            max(r.height_m) AS height_m,\n            min(r.position_en) AS position_en\n",
           "           FROM basketball_test.basket_player_roster r\n",
           "             JOIN basketball_test.schedule_team_dict d ON d.game_year = r.game_year AND d.team_name_basket = r.basket_team_name\n",
           "          WHERE r.identity_match_status = 'verified'::text\n",
           "          GROUP BY r.game_year, d.team_id_rosters, r.identity_id\n        )\\2"),
    "the end of the basket CTE")
  def <- edit(def, "THEN bk\\.height_m\\s+ELSE NULL(::numeric)?\\s+END AS height_m",
    "THEN COALESCE(bk.height_m, rs.height_m) ELSE NULL::numeric END AS height_m", "the height column")
  def <- edit(def, "THEN bk\\.position_en\\s+ELSE NULL(::text)?\\s+END AS position_en",
    "THEN COALESCE(bk.position_en, rs.position_en) ELSE NULL::text END AS position_en", "the position column")
  def <- edit(def, "(LEFT JOIN basketball_test\\.player_identities pi)",
    "LEFT JOIN roster_size rs ON p.identities = 1 AND rs.game_year = p.game_year AND rs.team_id = p.team_id AND rs.identity_id = p.identity_id\n     \\1",
    "the identities join")
  ddl <- paste0("CREATE OR REPLACE VIEW ", view, " AS\n", sub(";\\s*$", "", def), ";\n")
  writeLines(c(
    "-- Generated by scripts/apply_player_display_names_roster_height.R from the",
    "-- live definition of basketball_test.player_display_names_v (2026-11-12):",
    "-- height_m / position_en fall back to basket.co.il's team-page roster.",
    "", ddl), "sql/migrations/2026-11-12_player_display_names_roster_height.sql", useBytes = TRUE)
  x(ddl)

  if (!identical(cols(), before_cols)) stop("the view's columns changed")
  after <- snapshot()
  m <- merge(before, after, by = c("game_year", "team_id", "player_id"), suffixes = c(".b", ".a"))
  cat("rows before:", nrow(before), " after:", nrow(after), " matched:", nrow(m), "\n")
  if (nrow(m) != nrow(before) || nrow(after) != nrow(before)) stop("row set changed")
  if (any(m$names.b != m$names.a)) stop("a name or identity column changed")
  kept <- !is.na(m$height_m.b)
  if (any(m$height_m.a[kept] != m$height_m.b[kept])) stop("a season-stat height changed")
  if (any(!is.na(m$position_en.b) & (is.na(m$position_en.a) | m$position_en.a != m$position_en.b))) stop("a season-stat position changed")
  cat("names, identities and every existing height/position unchanged\n")
  for (gy in c(2026, 2027)) {
    s <- m[m$game_year == gy, ]
    cat(sprintf("%d: players %d, with a height %d -> %d\n", gy, nrow(s), sum(!is.na(s$height_m.b)), sum(!is.na(s$height_m.a))))
  }
  grant <- q(sprintf("SELECT has_table_privilege('app_readonly', '%s', 'SELECT') AS g", view))$g
  cat("app_readonly SELECT:", grant, "\n")
  if (!isTRUE(grant)) stop("app_readonly lost SELECT")
  t <- system.time(q(sprintf("SELECT team_id, player_id, height_m, position_en FROM %s WHERE game_year = 2027", view)))[["elapsed"]]
  cat(sprintf("season read 2027: %.2fs\n", t))
  filled <- q(sprintf("SELECT display_name, height_m, position_en FROM %s WHERE game_year = 2027 AND team_id = 2 ORDER BY height_m NULLS LAST, display_name", view))
  print(filled)
  ok <- TRUE
}, error = function(e) cat("FAILED:", conditionMessage(e), "\n"))

if (ok && confirm_apply) { x("COMMIT"); cat("COMMITTED\n") } else { x("ROLLBACK"); cat("ROLLED BACK\n") }
if (!ok) quit(status = 1)
