# Point player_display_names_v's Basket CTE at basket_player_registration
# (2026-11-12), which holds every registered player-season -- the stats-page
# players and the team-page-only ones -- instead of basket_player_season, which
# keeps only shooting totals. Same columns; the only rows that change are
# team-page-only players gaining a height and position.
#
# Built from the LIVE view definition (as apply_player_display_names_size.R):
# one edit, the CTE's FROM table, which must match exactly once.
#
# Dry run by default: one transaction, every gate, then ROLLBACK.
# CONFIRM_DISPLAY_NAMES_REGISTRATION=1 commits. The DDL that ran is written to
# sql/migrations/2026-11-12_player_display_names_registration.sql.

confirm_apply <- identical(Sys.getenv("CONFIRM_DISPLAY_NAMES_REGISTRATION", "0"), "1")
readRenviron("etl/.Renviron")
suppressPackageStartupMessages({ library(DBI); library(RPostgres) })
con <- dbConnect(Postgres(), host = Sys.getenv("PG_HOST"), port = 5432L,
  dbname = Sys.getenv("PG_DB"), user = Sys.getenv("PG_USER"),
  password = Sys.getenv("PG_PASS"), sslmode = "require", bigint = "numeric")
on.exit(dbDisconnect(con))
q <- function(sql) dbGetQuery(con, sql)
x <- function(sql) invisible(dbExecute(con, sql))
view <- "basketball_test.player_display_names_v"
cols <- function() q(sprintf(
  "SELECT attname FROM pg_attribute WHERE attrelid = '%s'::regclass AND attnum > 0 AND NOT attisdropped ORDER BY attnum", view))$attname
snapshot <- function() q(sprintf(
  "SELECT game_year, team_id, player_id, md5(row(game_year, team_id, player_id, identity_id, display_name, display_name_he, name_source)::text) AS names, identity_id, display_name, name_source, height_m, position_en FROM %s", view))
# Players whose registration is a team-page row (source = 'roster'): newly
# linked, so the view's "Basket name first" rule may now give them Basket's
# spelling. No other row may change a name.
roster_linked <- function() q(paste(
  "SELECT r.game_year, d.team_id_rosters AS team_id, r.identity_id",
  "FROM basketball_test.basket_player_registration r",
  "JOIN basketball_test.schedule_team_dict d ON d.game_year = r.game_year AND d.team_name_basket = r.basket_team_name",
  "WHERE r.source = 'roster' AND r.identity_match_status = 'verified'"))

cat("mode:", if (confirm_apply) "APPLY (commits)" else "DRY RUN (rolls back)", "\n")
x("BEGIN")
ok <- FALSE
tryCatch({
  x("SET LOCAL lock_timeout = '5s'")
  x("SET LOCAL statement_timeout = '120s'")
  before_cols <- cols()
  if (!all(c("height_m", "position_en") %in% before_cols)) stop("apply apply_player_display_names_size.R first")
  before <- snapshot()
  def <- q(sprintf("SELECT pg_get_viewdef('%s'::regclass, true) AS d", view))$d
  old_from <- "FROM basketball_test.basket_player_season b"
  hits <- gregexpr(old_from, def, fixed = TRUE)[[1]]
  if (length(hits) != 1 || hits[1] < 0) stop("expected exactly one '", old_from, "' in the view")
  def <- sub(old_from, "FROM basketball_test.basket_player_registration b", def, fixed = TRUE)
  if (grepl("basket_player_season", def, fixed = TRUE)) stop("the view still reads basket_player_season")
  ddl <- paste0("CREATE OR REPLACE VIEW ", view, " AS\n", sub(";\\s*$", "", def), ";\n")
  writeLines(c(
    "-- Generated by scripts/apply_player_display_names_registration.R from the",
    "-- live definition of basketball_test.player_display_names_v (2026-11-12):",
    "-- the Basket CTE reads basket_player_registration.",
    "", ddl), "sql/migrations/2026-11-12_player_display_names_registration.sql", useBytes = TRUE)
  x(ddl)

  if (!identical(cols(), before_cols)) stop("the view's columns changed")
  after <- snapshot()
  m <- merge(before, after, by = c("game_year", "team_id", "player_id"), suffixes = c(".b", ".a"))
  cat("rows before:", nrow(before), " after:", nrow(after), " matched:", nrow(m), "\n")
  if (nrow(m) != nrow(before) || nrow(after) != nrow(before)) stop("row set changed")
  renamed <- m$names.b != m$names.a
  linked <- paste(m$game_year, m$team_id, m$identity_id.b) %in%
    with(roster_linked(), paste(game_year, team_id, identity_id))
  allowed <- linked & m$name_source.b != "basket" & m$name_source.a == "basket" &
    !is.na(m$identity_id.b) & m$identity_id.b == m$identity_id.a
  if (any(renamed & !allowed)) {
    print(m[renamed & !allowed, c("game_year", "team_id", "player_id", "display_name.b", "display_name.a")])
    stop("a name or identity changed for a player who is not a newly linked team-page registration")
  }
  cat(sprintf("names now from Basket for %d newly linked team-page players; English spelling changes:\n", sum(renamed)))
  spelled <- renamed & m$display_name.b != m$display_name.a
  print(m[spelled, c("game_year", "team_id", "display_name.b", "display_name.a")], row.names = FALSE)
  kept <- !is.na(m$height_m.b)
  if (any(m$height_m.a[kept] != m$height_m.b[kept])) stop("a season-stat height changed")
  if (any(!is.na(m$position_en.b) & (is.na(m$position_en.a) | m$position_en.a != m$position_en.b))) stop("a season-stat position changed")
  cat("every other name and identity, and every existing height/position, unchanged\n")
  for (gy in c(2026, 2027)) {
    s <- m[m$game_year == gy, ]
    cat(sprintf("%d: players %d, with a height %d -> %d\n", gy, nrow(s), sum(!is.na(s$height_m.b)), sum(!is.na(s$height_m.a))))
  }
  grant <- q(sprintf("SELECT has_table_privilege('app_readonly', '%s', 'SELECT') AS g", view))$g
  cat("app_readonly SELECT:", grant, "\n")
  if (!isTRUE(grant)) stop("app_readonly lost SELECT")
  t <- system.time(q(sprintf("SELECT team_id, player_id, height_m, position_en FROM %s WHERE game_year = 2027", view)))[["elapsed"]]
  cat(sprintf("season read 2027: %.2fs\n", t))
  if (t > 1) stop("the 2027 read took over 1 s")
  filled <- q(sprintf("SELECT display_name, height_m, position_en FROM %s WHERE game_year = 2027 AND team_id = 2 ORDER BY height_m NULLS LAST, display_name", view))
  print(filled)
  ok <- TRUE
}, error = function(e) cat("FAILED:", conditionMessage(e), "\n"))

if (ok && confirm_apply) { x("COMMIT"); cat("COMMITTED\n") } else { x("ROLLBACK"); cat("ROLLED BACK\n") }
if (!ok) quit(status = 1)
