# Append basket.co.il's height and position to player_display_names_v
# (docs/shared_definitions.md, "Gameflow lineup name order"; user 2026-11-12:
# the database owns who is how tall, every consumer reads it from here).
#
# The new definition is built from the LIVE view definition, not from the
# 2026-11-01 migration file, so a later change made in the database is kept:
# two exact edits add max(height_m) / min(position_en) to the view's own
# basket CTE (verified rows, joined on identity AND team) and append
# height_m, position_en as the last two columns. CREATE OR REPLACE VIEW keeps
# app_readonly's grant when columns are only appended.
#
# Dry run by default: one transaction, every gate, then ROLLBACK.
# Set CONFIRM_DISPLAY_NAMES_SIZE=1 to COMMIT. Either way the DDL that ran is
# written to sql/migrations/2026-11-12_player_display_names_size.sql.

confirm_apply <- identical(Sys.getenv("CONFIRM_DISPLAY_NAMES_SIZE", "0"), "1")
readRenviron("etl/.Renviron")
suppressPackageStartupMessages({ library(DBI); library(RPostgres) })
con <- dbConnect(Postgres(), host = Sys.getenv("PG_HOST"), port = 5432L,
  dbname = Sys.getenv("PG_DB"), user = Sys.getenv("PG_USER"),
  password = Sys.getenv("PG_PASS"), sslmode = "require", bigint = "numeric")
on.exit(dbDisconnect(con))
q <- function(sql) dbGetQuery(con, sql)
x <- function(sql) invisible(dbExecute(con, sql))
view <- "basketball_test.player_display_names_v"
cols <- function() q(sprintf(
  "SELECT attname FROM pg_attribute WHERE attrelid = '%s'::regclass AND attnum > 0 AND NOT attisdropped ORDER BY attnum", view))$attname
fingerprint <- function(c) q(sprintf(
  "SELECT count(*) AS n, md5(string_agg(md5(row(%s)::text), '' ORDER BY game_year, team_id, player_id)) AS h FROM %s",
  paste(c, collapse = ","), view))

cat("mode:", if (confirm_apply) "APPLY (commits)" else "DRY RUN (rolls back)", "\n")
x("BEGIN")
ok <- FALSE
tryCatch({
  x("SET LOCAL lock_timeout = '5s'")
  x("SET LOCAL statement_timeout = '120s'")
  before <- cols()
  if (any(c("height_m", "position_en") %in% before)) stop("view already has height_m / position_en")
  fp_before <- fingerprint(before)
  def <- q(sprintf("SELECT pg_get_viewdef('%s'::regclass, true) AS d", view))$d

  edit <- function(text, pattern, replacement, what) {
    hits <- gregexpr(pattern, text, perl = TRUE)[[1]]
    if (length(hits) != 1 || hits[1] < 0) stop("expected exactly one match for ", what)
    sub(pattern, replacement, text, perl = TRUE)
  }
  def <- edit(def,
    "(AS name_he)(\\s+FROM basketball_test\\.basket_player_season b)",
    "\\1,\n            max(b.height_m) AS height_m,\n            min(b.position_en) AS position_en\\2",
    "the basket CTE")
  def <- edit(def,
    "(END AS name_source)(\\s+FROM pairs p)",
    "\\1,\n        CASE WHEN p.identities = 1 THEN bk.height_m ELSE NULL END AS height_m,\n        CASE WHEN p.identities = 1 THEN bk.position_en ELSE NULL END AS position_en\\2",
    "the final select")
  ddl <- paste0("CREATE OR REPLACE VIEW ", view, " AS\n", sub(";\\s*$", "", def), ";\n")
  writeLines(c(
    "-- Generated by scripts/apply_player_display_names_size.R from the live",
    "-- definition of basketball_test.player_display_names_v (2026-11-12):",
    "-- basket.co.il's height_m and position_en appended as the last columns.",
    "", ddl), "sql/migrations/2026-11-12_player_display_names_size.sql", useBytes = TRUE)
  x(ddl)

  after <- cols()
  cat("columns before:", length(before), " after:", length(after), "\n")
  if (!identical(after, c(before, "height_m", "position_en"))) stop("columns are not a pure append: ", paste(after, collapse = ","))
  fp_after <- fingerprint(before)
  cat("rows before:", fp_before$n, " after:", fp_after$n, "\n")
  if (!identical(fp_before$n, fp_after$n) || !identical(fp_before$h, fp_after$h))
    stop("the existing columns changed (row fingerprint differs)")
  cat("existing columns unchanged: row fingerprint identical\n")
  grant <- q(sprintf("SELECT has_table_privilege('app_readonly', '%s', 'SELECT') AS g", view))$g
  cat("app_readonly SELECT:", grant, "\n")
  if (!isTRUE(grant)) stop("app_readonly lost SELECT on the view")
  cov <- q(sprintf("SELECT game_year, count(*) AS players, count(height_m) AS with_height FROM %s WHERE game_year >= 2026 GROUP BY 1 ORDER BY 1", view))
  print(cov)
  t <- system.time(q(sprintf("SELECT team_id, player_id, height_m, position_en FROM %s WHERE game_year = 2027", view)))[["elapsed"]]
  cat(sprintf("season read 2027: %.2fs\n", t))
  print(q(sprintf("SELECT display_name, height_m, position_en FROM %s WHERE game_year = 2027 AND team_id = 2 ORDER BY height_m NULLS LAST, display_name", view)))
  ok <- TRUE
}, error = function(e) cat("FAILED:", conditionMessage(e), "\n"))

if (ok && confirm_apply) { x("COMMIT"); cat("COMMITTED\n") } else { x("ROLLBACK"); cat("ROLLED BACK\n") }
if (!ok) quit(status = 1)
